
"""LangGraph orchestrator for the Sprints AI Career and Assessment system."""

import logging
from typing import Literal

from langgraph.graph import StateGraph, START, END
from langgraph.checkpoint.memory import MemorySaver
from langgraph.types import interrupt, Command

from langchain_core.messages import HumanMessage, AIMessage
from langchain_openai import ChatOpenAI

from src.config import MAX_QUERY_REFORMULATIONS
from src.state import SprintsState

from src.agents.advisor_agent import AdvisorAgent
from src.agents.assessor_agent import AssessorAgent
from src.agents.profile_agent import ProfileAgent

from src.tools.db_queries import get_learner_profile_tool


logger = logging.getLogger(__name__)


class SprintsOrchestrator:
    """Route learner requests and manage agent workflows with HITL."""

    def __init__(
        self,
        llm=None,
        advisor=None,
        assessor=None,
        profile_agent=None,
    ):
        self.llm = llm or ChatOpenAI(
            model="gpt-4o-mini",
            temperature=0,
        )

        self.advisor = advisor or AdvisorAgent()
        self.assessor = assessor or AssessorAgent()
        self.profile_agent = profile_agent or ProfileAgent()

        graph = StateGraph(SprintsState)

        # Core nodes
        graph.add_node("router", self.router)
        graph.add_node("assessor", self.assessor_node)
        graph.add_node("profile", self.profile_node)
        graph.add_node("placement_gate", self.placement_gate)
        graph.add_node("finish", self.finish_node)

        # Advisor self-reflection nodes
        graph.add_node("advisor_retrieve", self.advisor_retrieve_node)
        graph.add_node("advisor_reflect", self.advisor_reflect_node)
        graph.add_node("advisor_rewrite", self.advisor_rewrite_node)
        graph.add_node("advisor_generate", self.advisor_generate_node)

        graph.add_edge(START, "router")

        graph.add_conditional_edges(
            "router",
            self.route,
            {
                "advisor": "advisor_retrieve",
                "assessor": "assessor",
                "profile": "profile",
            },
        )

        # Advisor self-reflection workflow
        graph.add_edge("advisor_retrieve", "advisor_reflect")

        graph.add_conditional_edges(
            "advisor_reflect",
            self.advisor_reflection_route,
            {
                "rewrite": "advisor_rewrite",
                "generate": "advisor_generate",
            },
        )

        graph.add_edge("advisor_rewrite", "advisor_retrieve")
        graph.add_edge("advisor_generate", "finish")

        # Other workflows
        graph.add_edge("assessor", "finish")
        graph.add_edge("profile", "placement_gate")
        graph.add_edge("placement_gate", "finish")

        graph.add_edge("finish", END)

        self.app = graph.compile(checkpointer=MemorySaver())

        logger.info("Orchestrator initialized successfully")

    # ---------------------------------------------------------
    # Message tracing helpers
    # ---------------------------------------------------------

    @staticmethod
    def log_human_message(content, thread_id=None):
        """Log an incoming HumanMessage."""

        logger.info(
            "HumanMessage | thread_id=%s | content=%s",
            thread_id,
            str(content),
        )

    @staticmethod
    def log_ai_message(content, agent):
        """Log an AIMessage generated by an agent."""

        logger.info(
            "AIMessage | agent=%s | content=%s",
            agent,
            str(content),
        )

    @staticmethod
    def log_tool_message(tool_name, result):
        """Log a ToolMessage-style trace for an executed tool."""

        logger.info(
            "ToolMessage | tool=%s | result=%s",
            tool_name,
            str(result),
        )

    # ---------------------------------------------------------
    # Router
    # ---------------------------------------------------------

    def router(self, state):
        """Classify the learner request into one of three intents."""

        logger.info("Router started")

        label = self.llm.invoke(
            "Classify as exactly advisor, assessor, or profile. "
            "Code submission or grading => assessor; "
            "salary, progress, employer, or placement => profile.\n"
            + state.get("query", "")
        ).content.strip().lower()

        if label not in {"advisor", "assessor", "profile"}:
            label = "advisor"

        self.log_ai_message(label, "router")

        logger.info("Router selected agent=%s", label)

        return {"intent": label}

    def route(self, state) -> Literal["advisor", "assessor", "profile"]:
        """Select the graph route."""

        return state["intent"]

    # ---------------------------------------------------------
    # Advisor: RAG + Self-Reflection
    # ---------------------------------------------------------

    def advisor_retrieve_node(self, state):
        """Retrieve relevant curriculum evidence."""

        logger.info("Advisor retrieval started")

        try:
            question = state.get("advisor_query") or state["query"]

            result = self.advisor.retrieve(question)

            docs = result.get("advisor_docs", [])
            context = result.get("advisor_context", "")

            previous_latency = state.get("retrieval_ms", 0.0)

            self.log_tool_message(
                "curriculum_rag",
                {
                    "status": "success",
                    "documents_retrieved": len(docs),
                },
            )

            return {
                "advisor_docs": docs,
                "advisor_context": context,
                "retrieved_context": context,
                "retrieval_ms": round(
                    previous_latency + result.get("retrieval_ms", 0.0),
                    2,
                ),
            }

        except Exception as exc:
            logger.exception("Advisor retrieval failed")

            self.log_tool_message(
                "curriculum_rag",
                {
                    "status": "error",
                    "error": type(exc).__name__,
                },
            )

            return {
                "advisor_docs": [],
                "advisor_context": "",
                "retrieved_context": "",
                "error": str(exc),
            }

    def advisor_reflect_node(self, state):
        """Evaluate whether retrieved evidence is sufficient."""

        logger.info("Advisor reflection started")

        try:
            sufficient = self.advisor.reflect(
                state["query"],
                state.get("advisor_context", ""),
            )

            logger.info(
                "Advisor reflection result | sufficient=%s | retries=%s",
                sufficient,
                state.get("advisor_retry_count", 0),
            )

            return {
                "advisor_sufficient": sufficient,
            }

        except Exception as exc:
            logger.exception("Advisor reflection failed")

            return {
                "advisor_sufficient": False,
                "error": str(exc),
            }

    def advisor_reflection_route(self, state):
        """Choose between query rewriting and answer generation."""

        if state.get("advisor_sufficient", False):
            logger.info("Reflection decision: generate answer")
            return "generate"

        retries = state.get("advisor_retry_count", 0)

        if retries < MAX_QUERY_REFORMULATIONS:
            logger.info(
                "Reflection decision: rewrite query | retry=%s",
                retries + 1,
            )
            return "rewrite"

        logger.warning(
            "Maximum self-reflection retries reached: %s",
            MAX_QUERY_REFORMULATIONS,
        )

        return "generate"

    def advisor_rewrite_node(self, state):
        """Rewrite the query to improve curriculum retrieval."""

        logger.info("Advisor query rewriting started")

        try:
            current_query = (
                state.get("advisor_query") or state["query"]
            )

            rewritten = self.advisor.rewrite_query(current_query)

            if not rewritten:
                rewritten = current_query

            retry_count = state.get("advisor_retry_count", 0) + 1

            logger.info(
                "Advisor query rewritten | retry=%s",
                retry_count,
            )

            return {
                "advisor_query": rewritten,
                "advisor_retry_count": retry_count,
            }

        except Exception as exc:
            logger.exception("Advisor query rewriting failed")

            return {
                "advisor_retry_count": MAX_QUERY_REFORMULATIONS,
                "error": str(exc),
            }

    def advisor_generate_node(self, state):
        """Generate an answer using retrieved curriculum context."""

        logger.info("Advisor answer generation started")

        try:
            answer = self.advisor.generate_answer(
                state["query"],
                state.get("advisor_context", ""),
            )

            self.log_ai_message(answer, "advisor")

            return {
                "answer": answer,
                "messages": [
                    AIMessage(content=str(answer))
                ],
            }

        except Exception as exc:
            logger.exception("Advisor answer generation failed")

            answer = (
                "Unable to verify curriculum information. "
                f"Reason: {type(exc).__name__}"
            )

            self.log_ai_message(answer, "advisor")

            return {
                "answer": answer,
                "error": str(exc),
                "messages": [
                    AIMessage(content=answer)
                ],
            }

    # ---------------------------------------------------------
    # Assessor
    # ---------------------------------------------------------

    def assessor_node(self, state):
        """Execute and assess a learner Python submission."""

        logger.info("Assessor agent started")

        try:
            result = self.assessor.assess(
                state["query"],
                state.get("code", ""),
            )

            answer = str(result)

            self.log_ai_message(answer, "assessor")

            return {
                "assessment": result,
                "answer": answer,
                "messages": [
                    AIMessage(content=answer)
                ],
            }

        except Exception as exc:
            logger.exception("Assessor agent failed")

            answer = (
                "Unable to verify the code assessment. "
                f"Reason: {type(exc).__name__}"
            )

            self.log_ai_message(answer, "assessor")

            return {
                "assessment": {
                    "status": "Unable to verify",
                    "reason": type(exc).__name__,
                },
                "answer": answer,
                "error": str(exc),
                "messages": [
                    AIMessage(content=answer)
                ],
            }

    # ---------------------------------------------------------
    # Learner Profile
    # ---------------------------------------------------------

    def profile_node(self, state):
        """Retrieve learner information and prepare placement review."""

        student_id = state.get("student_id", "")

        logger.info("Profile agent started")

        try:
            agent_result = self.profile_agent.answer(
                f"Student ID: {student_id}\n"
                f"Learner question: {state.get('query', '')}"
            )

            logger.info("Profile agent completed")

            profile = get_learner_profile_tool.invoke({
                "student_id": student_id
            })

            # Log a safe summary instead of exposing private learner data.
            if isinstance(profile, dict):
                tool_summary = {
                    "status": profile.get("status", "unknown"),
                    "records_found": len(profile.get("rows", [])),
                }
            else:
                tool_summary = {
                    "status": "invalid_response",
                }

            self.log_tool_message(
                "get_learner_profile_tool",
                tool_summary,
            )

            if not isinstance(profile, dict):
                raise ValueError("Invalid learner profile response")

            if profile.get("status") != "ok":
                raise ValueError("Learner profile could not be verified")

            if agent_result.get("status") != "ok":
                raise ValueError("Profile agent could not verify the answer")

            answer = agent_result.get(
                "answer",
                "Unable to verify learner information.",
            )

            profile["agent_answer"] = answer

            self.log_ai_message(answer, "profile")

            return {
                "learner_profile": profile,
                "answer": answer,
                "messages": [
                    AIMessage(content=answer)
                ],
            }

        except Exception as exc:
            logger.exception("Profile agent or database tool failed")

            answer = (
                "Unable to verify learner profile. "
                "Placement cannot proceed."
            )

            self.log_ai_message(answer, "profile")

            return {
                "learner_profile": {
                    "status": "Unable to verify",
                    "rows": [],
                },
                "answer": answer,
                "error": str(exc),
                "messages": [
                    AIMessage(content=answer)
                ],
            }

    # ---------------------------------------------------------
    # Human-in-the-loop placement approval
    # ---------------------------------------------------------

    def placement_gate(self, state):
        """Require human approval before a Tier-1 placement proceeds."""

        logger.info("Placement approval gate started")

        profile = state.get("learner_profile", {})

        if profile.get("status") != "ok":
            answer = (
                "Unable to verify learner profile. "
                "Placement cannot proceed."
            )

            self.log_ai_message(answer, "placement_gate")

            return {
                "answer": answer,
                "needs_human_approval": False,
                "messages": [
                    AIMessage(content=answer)
                ],
            }

        learner = profile.get("learner", {})

        preferred_employers = str(
            learner.get("preferred_employers", "")
        ).lower()

        query = state.get("query", "").lower()

        tier1 = (
            "fawry" in preferred_employers
            or "fawry" in query
        )

        if not tier1:
            answer = (
                "Learner profile retrieved successfully. "
                "No Tier-1 approval required."
            )

            logger.info("No Tier-1 approval required")
            self.log_ai_message(answer, "placement_gate")

            return {
                "answer": answer,
                "needs_human_approval": False,
                "messages": [
                    AIMessage(content=answer)
                ],
            }

        logger.info("Human approval requested for Tier-1 placement")

        decision = interrupt({
            "type": "placement_approval_required",
            "message": (
                "Fawry is a Tier-1 partner. "
                "Human approval is required before proceeding."
            ),
            "student_id": state.get("student_id"),
            "profile": profile,
        })

        approved = str(decision).strip().lower() in {
            "approve",
            "approved",
            "yes",
            "true",
        }

        if approved:
            logger.info("Human placement decision: approved")

            answer = "Human review approved. Placement may proceed."

            self.log_ai_message(answer, "placement_gate")

            return {
                "human_decision": "approved",
                "needs_human_approval": False,
                "placement": {
                    "status": "approved",
                    "partner": "Fawry",
                },
                "answer": answer,
                "messages": [
                    AIMessage(content=answer)
                ],
            }

        logger.info("Human placement decision: rejected")

        answer = "Human review rejected. Placement must not proceed."

        self.log_ai_message(answer, "placement_gate")

        return {
            "human_decision": "rejected",
            "needs_human_approval": False,
            "placement": {
                "status": "rejected",
                "partner": "Fawry",
            },
            "answer": answer,
            "messages": [
                AIMessage(content=answer)
            ],
        }

    # ---------------------------------------------------------
    # Finish
    # ---------------------------------------------------------

    def finish_node(self, state):
        """Preserve accumulated messages and final answer."""

        logger.info("Orchestrator workflow completed")

        return {
            "answer": state.get("answer", "Unable to verify"),
        }

    # ---------------------------------------------------------
    # Public interface
    # ---------------------------------------------------------

    def invoke(self, query, student_id, thread_id, code=""):
        """Run the graph using a persistent thread identifier."""

        self.log_human_message(query, thread_id)

        config = {
            "configurable": {
                "thread_id": thread_id
            }
        }

        return self.app.invoke(
            {
                "query": query,
                "student_id": student_id,
                "thread_id": thread_id,
                "code": code,
                "messages": [
                    HumanMessage(content=query)
                ],
                "advisor_retry_count": 0,
                "retrieval_ms": 0.0,
            },
            config=config,
        )

    def approve_placement(self, decision, thread_id):
        """Resume a paused graph after a human decision."""

        self.log_human_message(
            f"Placement decision: {decision}",
            thread_id,
        )

        return self.app.invoke(
            Command(resume=decision),
            config={
                "configurable": {
                    "thread_id": thread_id
                }
            },
        )
